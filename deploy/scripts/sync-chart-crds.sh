#!/usr/bin/env bash
# Copies the generated CRDs (deploy/crd/*.yaml, written by crdgen) into the
# chart as *templates* (deploy/charts/weebo-forgejo/templates/crds/), run by
# `task recu`. Helm's `crds/` directory is installed once and never
# upgraded; templates are, so a chart upgrade also upgrades the CRDs.
#
# Each CRD is wrapped so that:
#   - it only renders when `.Values.crds.install` is true (GitOps setups or
#     clusters where CRDs are managed out of band turn it off);
#   - it carries `helm.sh/resource-policy: keep`: `helm uninstall` (or a
#     render with crds.install=false) never deletes a CRD, and with it every
#     CR of the cluster.
#
# Usage: deploy/scripts/sync-chart-crds.sh [SRC_DIR] [DEST_DIR]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SRC="${1:-$ROOT/deploy/crd}"
DEST="${2:-$ROOT/deploy/charts/weebo-forgejo/templates/crds}"

shopt -s nullglob
files=("$SRC"/*.yaml)
[ "${#files[@]}" -gt 0 ] || { echo "no CRD in $SRC" >&2; exit 1; }

mkdir -p "$DEST"
rm -f "$DEST"/*.yaml

for src in "${files[@]}"; do
  name="$(basename "$src")"
  # A literal `{{` would be parsed by Helm's template engine.
  if grep -q '{{' "$src"; then
    echo "$src contains '{{': escape it before wrapping it as a Helm template" >&2
    exit 1
  fi
  if ! head -n 3 "$src" | grep -qx 'metadata:'; then
    echo "$src: expected 'metadata:' within the first 3 lines (crdgen layout changed?)" >&2
    exit 1
  fi
  {
    echo "{{- if .Values.crds.install }}"
    echo "# Generated by \`task recu\` from deploy/crd/$name: do not edit."
    # The metadata block of a crdgen CRD is only `name:`; labels and
    # annotations are added right after it.
    awk '
      { print }
      /^metadata:$/ && !done { in_meta = 1; next }
      in_meta && /^  name: / {
        print "  labels:"
        print "    {{- include \"weebo-forgejo.labels\" . | nindent 4 }}"
        print "  annotations:"
        print "    # Never deleted by helm uninstall: that would delete every CR."
        print "    helm.sh/resource-policy: keep"
        in_meta = 0; done = 1
      }
      in_meta && /^  (labels|annotations):/ {
        print "unexpected metadata." $1 " in generated CRD" > "/dev/stderr"
        exit 1
      }
    ' "$src"
    echo "{{- end }}"
  } > "$DEST/$name"
done

echo "wrapped ${#files[@]} CRDs into ${DEST#"$ROOT"/}"
